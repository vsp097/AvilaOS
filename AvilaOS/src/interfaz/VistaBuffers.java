    private void btnCrearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearActionPerformed
                try {
            if (cantidad >= buffers.length) {
                throw new IllegalArgumentException("Ya no se pueden crear mas buffers (maximo " + buffers.length + ")");
            }
            if (cmbAnfitrion.getItemCount() == 0) {
                throw new IllegalArgumentException("No hay computadores");
            }
            String nombre = Validaciones.leerTexto(txtNombre.getText(), "Nombre del buffer", 30);
            for (int i = 0; i < cantidad; i++) {
                if (buffers[i].getNombre().equalsIgnoreCase(nombre)) {
                    throw new IllegalArgumentException("Ya existe un buffer con ese nombre");
                }
            }
            int capacidad = Validaciones.leerEntero(txtCapacidad.getText(), "Capacidad", 1, 1000);
            int pos = cmbAnfitrion.getSelectedIndex();
            Computador anfitrion = computadores[pos];

            //el buffer ocupa RAM en su anfitrion, si no alcanza no se crea
            Buffer b = new Buffer(nombre, capacidad);
            if (!b.setComputador(anfitrion)) {
                throw new IllegalArgumentException("El Computador " + (pos + 1) + " no tiene RAM suficiente. Libre: "
                        + anfitrion.getRam() + ", el buffer necesita: " + capacidad);
            }

            int indice = cantidad;
            buffers[cantidad] = b;
            cantidad++;
            lblMensaje.setText("Buffer " + nombre + " creado en Computador " + (pos + 1)
                    + ". RAM libre: " + anfitrion.getRam());
            if (listener != null) {
                listener.bufferCreado(b, indice);
            }
            txtNombre.setText("");
            txtCapacidad.setText("");
        } catch (IllegalArgumentException e) {
            //dato invalido: aviso y la ventana sigue abierta
            JOptionPane.showMessageDialog(this, e.getMessage(), "Dato invalido", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnCrearActionPerformed


