        //para los datos del proceso
    public void mostrar(PCB p) {
        if (p == null) {
            datos.setText("Ningun proceso seleccionado");
            return;
        }
        datos.setText("<html>"
                + "ID: " + p.getId() + "<br>"
                + "Nombre: " + p.getname() + "<br>"
                + "Estado: " + p.getstate() + "<br>"
                + "Tipo: " + p.gettype() + "<br>"
                + "PC: " + p.getpc() + "<br>"
                + "Memoria: " + p.getmem() + " MB<br>"
                + "Deadline: " + p.getdeadline() + "<br>"
                + "Tiempo restante: " + p.getime()
                + "</html>");
    }

